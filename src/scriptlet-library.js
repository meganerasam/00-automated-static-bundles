// src/scriptlet-library.js — assemble the scriptlet CODE for the scriptlets the DB
// references, from @adguard/scriptlets (uBO-compatible names). Reliable deliverable:
// used-scriptlets.json (names). Code: each scriptlet's source via
// scriptlets.getScriptletFunction(name).toString(); aliases (e.g. "aopr") are
// resolved to their canonical name through the uBO->AdG converter.
//
// NOTE: an extracted function's source references shared helpers that live in the
// AdGuard runtime, so it is REFERENCE code to restyle per build, not a drop-in
// standalone. The DB + names are the load-bearing output; the code is a head start.

const safe = (fn) => { try { return fn(); } catch { return null; } };

export async function buildScriptletLibrary(usedNames) {
  const { scriptlets } = await import('@adguard/scriptlets');
  const conv = await import('@adguard/scriptlets/converters').catch(() => null);

  const canonicalOf = (name) => {
    if (!conv?.convertUboToAdg) return null;
    const out = safe(() => conv.convertUboToAdg(`##+js(${name})`));
    const rule = Array.isArray(out) ? out[0] : out;
    const m = rule && /scriptlet\(\s*'([^']+)'/.exec(rule);
    return m ? m[1].replace(/^(ubo|abp)-/, '') : null;
  };

  const header = [
    '/* Scriptlet library — generated by Automated Static Bundle from @adguard/scriptlets.',
    ' * uBO-compatible names. REFERENCE sources (helpers live in the AdGuard runtime):',
    ' * restyle into your build\'s main-world runtime. Ship the SAME version the DB used.',
    ` * Referenced by the DB: ${usedNames.length} scriptlets. */`,
    '',
  ].join('\n');

  const resolved = [];
  const missing = [];
  const bodies = [];

  for (const name of usedNames) {
    let fn = safe(() => scriptlets.getScriptletFunction(name));
    let via = name;
    if (typeof fn !== 'function') {
      const canonical = canonicalOf(name);
      if (canonical) { fn = safe(() => scriptlets.getScriptletFunction(canonical)); via = canonical; }
    }
    if (typeof fn === 'function') {
      resolved.push(name);
      const tag = via === name ? name : `${name}  (canonical: ${via})`;
      bodies.push(`/* ${tag} */\nexport const ${jsId(name)} = ${fn.toString()};`);
    } else {
      missing.push(name);
    }
  }

  const code = header
    + (missing.length ? `// NOT resolved (implement manually): ${missing.join(', ')}\n\n` : '')
    + bodies.join('\n\n') + '\n';

  return { code, resolved, missing };
}

// A valid JS identifier for the export (camel-ish from the scriptlet name).
function jsId(name) {
  const id = name.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''));
  return /^[a-zA-Z_$]/.test(id) ? id : `_${id}`;
}
